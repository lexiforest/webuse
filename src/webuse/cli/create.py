import argparse
from pathlib import Path

from .utils import print_jsonl


def project_config_yaml(project_name: str) -> str:
    return f"""name: {project_name}
user_agent: chrome
robots_txt: true
llm: {{}}
# llm:
#   model: gpt-4.1-mini
#   api_key: sk-...
#   base_url: https://api.openai.com/v1
concurrency:
  limit: 5
  per_domain: 1
log:
  level: info
  file: stderr
  append: true
"""


def _project_template(project_name: str, *, package_name: str) -> dict[str, str]:
    run_command = (
        f"cd ..\nwebuse crawl {package_name} --spider books -o books.jsonl"
        if package_name.isidentifier()
        else "webuse crawl --spider books -o books.jsonl"
    )
    return {
        "README.md": f"""# {project_name}

Generated by `webuse create`.

[Webuse on GitHub](https://github.com/lexiforest/webuse)

## Generate a Spider

```bash
webuse gen books https://books.toscrape.com/
{run_command}
```

## Fetch

To test a single URL:

```bash
webuse fetch https://books.toscrape.com/ --css "article.product_pod h3 a" --attr title --all
```

## Items

`webuse gen` puts the item model and cleanup pipeline in the generated spider
module, such as `spiders/books.py`.
Configure item processing in each spider's `items.pipelines` section, or its
Python `pipelines` attribute.
""",
        ".gitignore": """.webuse/
selectors.json
output.jsonl
*.sqlite
*.sqlite-*
""",
        "__init__.py": "",
        "spiders/__init__.py": "",
        "webuse.yaml": project_config_yaml(project_name),
    }


def create_command(args: argparse.Namespace) -> int:
    target = Path(args.directory)
    project_name = args.name or target.name

    if target.exists() and not target.is_dir():
        raise SystemExit(f"create target exists and is not a directory: {target}")
    if target.exists() and any(target.iterdir()) and not args.force:
        raise SystemExit(
            f"create target is not empty: {target}. Use --force to write scaffold files anyway."
        )

    files = _project_template(project_name, package_name=target.name)

    for relative_path in files:
        path = target / relative_path
        if path.exists() and not args.force:
            raise SystemExit(f"refusing to overwrite existing file: {path}")

    target.mkdir(parents=True, exist_ok=True)
    (target / ".webuse").mkdir(exist_ok=True)
    (target / "spiders").mkdir(exist_ok=True)

    written: list[str] = []
    for relative_path, content in files.items():
        path = target / relative_path
        path.write_text(content, encoding="utf-8")
        written.append(relative_path)

    print_jsonl(
        [
            {
                "path": str(target),
                "project": project_name,
                "files": written,
            }
        ]
    )
    return 0


def register(subparsers: argparse._SubParsersAction) -> None:
    create_parser = subparsers.add_parser("create")
    create_parser.add_argument("directory")
    create_parser.add_argument("--name")
    create_parser.add_argument("--force", action="store_true")
    create_parser.set_defaults(func=create_command)
